def build(nodes):
    out = []
    for n in nodes:
        src = {c['key']: c for c in n['translatableContent']}
        g = GUIDES.get(src['handle']['value'])
        if not g:
            continue
        vals = {'title': g['title'], 'body_html': g['body'], 'summary_html': g['summary'],
                'meta_title': g['meta_title'], 'meta_description': g['meta_description']}
        out.append({'id': n['resourceId'], 't': [
            {'locale': 'ar', 'key': k, 'value': v, 'translatableContentDigest': src[k]['digest']}
            for k, v in vals.items() if k in src]})
    return out


