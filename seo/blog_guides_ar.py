def faq_block(items):
    dl = ''.join(f'<dt>{html.escape(q)}</dt><dd>{html.escape(a)}</dd>' for q, a in items)
    ld = {'@context': 'https://schema.org', '@type': 'FAQPage', 'inLanguage': 'ar',
          'mainEntity': [{'@type': 'Question', 'name': q,
                          'acceptedAnswer': {'@type': 'Answer', 'text': a}} for q, a in items]}
    return ('<h2>أسئلة شائعة</h2><dl class="faq">' + dl + '</dl>'
            '<script type="application/ld+json">' + json.dumps(ld, ensure_ascii=False) + '</script>')


def cta(title, text, href, label):
    return (f'<div class="cta"><h2>{title}</h2><p>{text}</p>'
            f'<a class="btn" href="{href}">{label}</a></div>')


