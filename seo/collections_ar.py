def main():
    dump = json.load(open(sys.argv[1]))['data']
    digests = {}
    for group in dump.values():
        for n in group['nodes']:
            digests[n['resourceId']] = {c['key']: c['digest'] for c in n['translatableContent']}
    out = {}
    for table in (COLLECTIONS, SHOP, PAGES):
        for rid, fields in table.items():
            out[rid] = [{'locale': 'ar', 'key': k, 'value': v,
                         'translatableContentDigest': digests[rid][k]} for k, v in fields.items()]
    print(json.dumps(out, ensure_ascii=False))


if __name__ == '__main__':
    main()
